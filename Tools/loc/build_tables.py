#!/usr/bin/env python3
"""
Builds Assets/RetroSk8/Scripts/Core/LocTables.cs from Tools/loc/es.tsv and ja.tsv (Phase 28).

Each .tsv line is "English<TAB>translation", with "\\n" for line breaks. The check refuses entries whose
{0}/{1}... placeholders don't match the English, and reports strings the game uses that a table doesn't cover
(see extract_strings.py). Run from the repo root:  python3 Tools/loc/build_tables.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LOC = os.path.join(ROOT, "Tools", "loc")
OUT = os.path.join(ROOT, "Assets", "RetroSk8", "Scripts", "Core", "LocTables.cs")
LANGS = [("es", "Spanish"), ("ja", "Japanese")]
PH = re.compile(r"\{(\d)\}")


def load(code):
    path = os.path.join(LOC, code + ".tsv")
    rows, problems = [], []
    if not os.path.exists(path):
        return rows, ["%s.tsv is missing" % code]
    seen = set()
    for n, line in enumerate(open(path, encoding="utf-8"), 1):
        line = line.rstrip("\n").rstrip("\r")
        if not line.strip() or line.startswith("#"):
            continue
        if line.count("\t") != 1:
            problems.append("%s.tsv:%d needs exactly one tab" % (code, n))
            continue
        en, tr = line.split("\t")
        if not en or not tr.strip():
            problems.append("%s.tsv:%d is empty" % (code, n))
            continue
        # A translation may leave out a placeholder (an English plural "S" has no place in Japanese) but never adds one.
        if not set(PH.findall(tr)) <= set(PH.findall(en)):
            problems.append("%s.tsv:%d placeholders differ: %s | %s" % (code, n, en, tr))
            continue
        if en in seen:
            continue
        seen.add(en)
        rows.append((en, tr))
    return rows, problems


def main():
    strings = []
    sp = os.path.join(LOC, "strings.txt")
    if os.path.exists(sp):
        strings = [l.rstrip("\n") for l in open(sp, encoding="utf-8") if l.strip()]
    parts = []
    all_problems = []
    for code, name in LANGS:
        rows, problems = load(code)
        all_problems += problems
        have = {en for en, _ in rows}
        missing = [s for s in strings if s not in have]
        print("%s: %d entries, %d of %d game strings missing, %d problems" % (code, len(rows), len(missing), len(strings), len(problems)))
        body = "\n".join(en + "\t" + tr for en, tr in rows)
        parts.append((name, body.replace('"', '""')))
    for p in all_problems[:40]:
        print("  ", p)

    cs = ["// <auto-generated> Phase 28: built by Tools/loc/build_tables.py from Tools/loc/*.tsv. Edit the .tsv files, not this.",
          "namespace RetroSk8.Core",
          "{",
          "    /// <summary>The translation tables (English TAB translation per line; \\n is a line break).</summary>",
          "    public static class LocTables",
          "    {",
          "        public static string For(Lang lang)",
          "        {",
          "            switch (lang)",
          "            {"]
    for name, _ in parts:
        cs.append("                case Lang.%s: return %s;" % (name, name))
    cs += ["                default: return \"\";",
           "            }",
           "        }",
           ""]
    for name, body in parts:
        cs.append("        public const string %s = @\"%s\";" % (name, body))
        cs.append("")
    cs += ["    }", "}", ""]
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(cs))
    print("wrote", os.path.relpath(OUT, ROOT))
    return 1 if all_problems else 0


if __name__ == "__main__":
    sys.exit(main())
